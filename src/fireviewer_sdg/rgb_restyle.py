"""Deterministic, composition-locked RGB restyling for FireViewer captures.

The source capture is immutable.  This module prepares a single-image ComfyUI
job and admits a derived RGB only after co-registration checks pass.  Depth,
normals, masks, camera data, geolocation and fire/smoke metadata are never
rewritten or regenerated by this workflow.
"""

