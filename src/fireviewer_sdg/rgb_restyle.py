class RestyleContractError(RuntimeError):
    """Raised when a source, workflow or contract violates the lock."""


class AdmissionRejected(RestyleContractError):
    """Raised when a generated candidate fails composition admission."""

    def __init__(self, report: Mapping[str, Any]) -> None:
        self.report = dict(report)
        failed = [name for name, passed in report.get("gates", {}).items() if not passed]
        super().__init__("restyle candidate rejected: " + ", ".join(failed))


@dataclass(frozen=True)
class CaptureInventory:
    capture_dir: Path
    capture_id: str
    width_px: int
    height_px: int
    source_files: dict[str, dict[str, Any]]
    source_binding_sha256: str
    expected_fire_visible: bool
    sample_kind: str
    protected_pixel_count: int
    fire_pixel_count: int
    smoke_pixel_count: int
    target_witness: dict[str, Any]

    def as_dict(self, *, include_local_path: bool = False) -> dict[str, Any]:
        payload: dict[str, Any] = {
            "schema": "fireviewer.rgb-restyle.capture-inventory.v1",
            "capture_id": self.capture_id,
            "width_px": self.width_px,
            "height_px": self.height_px,
            "source_files": self.source_files,
            "source_binding_sha256": self.source_binding_sha256,
            "expected_fire_visible": self.expected_fire_visible,
            "sample_kind": self.sample_kind,
            "protected_pixel_count": self.protected_pixel_count,
            "fire_pixel_count": self.fire_pixel_count,
            "smoke_pixel_count": self.smoke_pixel_count,
            "target_witness": self.target_witness,
        }
        if include_local_path:
            payload["capture_dir"] = str(self.capture_dir)
        return payload


def canonical_json_bytes(value: Any) -> bytes:
    return json.dumps(
        value,
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
    ).encode("utf-8")


def sha256_bytes(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as source:
        while chunk := source.read(1024 * 1024):
            digest.update(chunk)
    return digest.hexdigest()


def _load_json(path: Path) -> dict[str, Any]:
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise RestyleContractError(f"invalid JSON file {path}: {exc}") from exc
    if not isinstance(value, dict):
        raise RestyleContractError(f"JSON root must be an object: {path}")
    return value


def _write_json_atomic(path: Path, value: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + f".tmp-{os.getpid()}")
    temporary.write_bytes(canonical_json_bytes(value) + b"\n")
    os.replace(temporary, path)


def _file_record(path: Path) -> dict[str, Any]:
    return {
        "sha256": sha256_file(path),
        "size_bytes": path.stat().st_size,
    }


def _version_tuple(value: str) -> tuple[int, ...]:
    numbers = re.findall(r"\d+", value)
    return tuple(int(number) for number in numbers[:3])


def _merge_contract(base: Mapping[str, Any], overlay: Mapping[str, Any]) -> dict[str, Any]:
    merged: dict[str, Any] = dict(base)
    for key, value in overlay.items():
        if key == "extends":
            continue
        if isinstance(value, Mapping) and isinstance(merged.get(key), Mapping):
            merged[key] = _merge_contract(merged[key], value)
        else:
            merged[key] = value
    return merged


def load_contract(path: Path = DEFAULT_CONTRACT_PATH) -> dict[str, Any]:
    resolved = path.resolve()
    overlay = _load_json(resolved)
    parent_hash: str | None = None
    if isinstance(overlay.get("extends"), str):
        parent = (resolved.parent / overlay["extends"]).resolve()
        if parent.parent != resolved.parent or not parent.is_file():
            raise RestyleContractError("contract extension must be a sibling JSON contract")
        base = load_contract(parent)
        parent_hash = str(base["_contract_sha256"])
        contract = _merge_contract(
            {key: value for key, value in base.items() if not key.startswith("_")}, overlay
        )
    else:
        contract = overlay
    if contract.get("schema") != "fireviewer.rgb-restyle.contract.v1":
        raise RestyleContractError("unsupported RGB restyle contract schema")
    if contract.get("status") not in {"locked-pilot-only", "locked-batch-validation"}:
        raise RestyleContractError("the RGB restyle contract is not locked for controlled use")
    source = contract.get("source_contract")
    engine = contract.get("engine")
    lock = contract.get("composition_lock")
    if not all(isinstance(value, dict) for value in (source, engine, lock)):
        raise RestyleContractError("contract source, engine and composition lock are required")
    if source.get("overwrite_source") is not False:
        raise RestyleContractError("source overwrite must remain disabled")
    if engine.get("control_adapters") or engine.get("lora_adapters"):
        raise RestyleContractError("v1 forbids ControlNet and LoRA adapters")
    workflow_relative = engine.get("api_workflow")
    workflow_sha = engine.get("api_workflow_sha256")
    if not isinstance(workflow_relative, str) or not SHA256_PATTERN.fullmatch(str(workflow_sha)):
        raise RestyleContractError("workflow path and SHA-256 are required")
    workflow_path = (PROJECT_ROOT / workflow_relative).resolve()
    if not workflow_path.is_file():
        raise RestyleContractError(f"locked workflow is missing: {workflow_path}")
    if sha256_file(workflow_path) != workflow_sha:
        raise RestyleContractError("locked ComfyUI workflow SHA-256 mismatch")
    for model in engine.get("models", []):
        if not isinstance(model, dict):
            raise RestyleContractError("invalid model lock entry")
        if not SHA256_PATTERN.fullmatch(str(model.get("sha256", ""))):
            raise RestyleContractError(f"invalid model SHA-256 for {model.get('role')}")
        if not isinstance(model.get("size_bytes"), int) or model["size_bytes"] <= 0:
            raise RestyleContractError(f"invalid model size for {model.get('role')}")
    validate_workflow_structure(_load_json(workflow_path), contract)
    contract["_contract_sha256"] = sha256_bytes(
        canonical_json_bytes(
            {
                "overlay_sha256": sha256_file(resolved),
                "parent_contract_sha256": parent_hash,
                "resolved_contract": contract,
            }
        )
    )
    contract["_contract_path"] = str(resolved)
    contract["_workflow_path"] = str(workflow_path)
    return contract


def validate_workflow_structure(
    workflow: Mapping[str, Any], contract: Mapping[str, Any]
) -> None:
    if not workflow:
        raise RestyleContractError("ComfyUI workflow is empty")
    classes: list[str] = []
    for node_id, node in workflow.items():
        if not isinstance(node_id, str) or not isinstance(node, dict):
            raise RestyleContractError("ComfyUI API workflow nodes must be string-keyed objects")
        class_type = node.get("class_type")
        if not isinstance(class_type, str) or not isinstance(node.get("inputs"), dict):
            raise RestyleContractError(f"invalid ComfyUI node {node_id}")
        classes.append(class_type)
    required = set(contract["engine"]["required_node_classes"])
    if set(classes) != required:
        missing = sorted(required - set(classes))
        unexpected = sorted(set(classes) - required)
        raise RestyleContractError(
            f"workflow node lock mismatch; missing={missing}, unexpected={unexpected}"
        )
    by_class: dict[str, list[Mapping[str, Any]]] = {}
    for node in workflow.values():
        by_class.setdefault(node["class_type"], []).append(node)
    engine = contract["engine"]
    if by_class["UNETLoader"][0]["inputs"].get("unet_name") != engine["models"][0]["comfy_name"]:
        raise RestyleContractError("workflow diffusion model differs from the contract")
    if by_class["KSamplerSelect"][0]["inputs"].get("sampler_name") != engine["sampler"]:
        raise RestyleContractError("workflow sampler differs from the contract")
    if by_class["Flux2Scheduler"][0]["inputs"].get("steps") != engine["steps"]:
        raise RestyleContractError("workflow step count differs from the contract")
    if float(by_class["CFGGuider"][0]["inputs"].get("cfg")) != float(engine["cfg"]):
        raise RestyleContractError("workflow CFG differs from the contract")
    serialized = json.dumps(workflow, ensure_ascii=False)
    present = {placeholder for placeholder in PLACEHOLDERS if placeholder in serialized}
    if present != PLACEHOLDERS:
        raise RestyleContractError(
            f"workflow placeholders differ from lock: {sorted(present)}"
        )


def _load_npz_array(path: Path) -> np.ndarray:
    try:
        with np.load(path, allow_pickle=False) as archive:
            if "data" in archive.files:
                array = archive["data"]
            elif len(archive.files) == 1:
                array = archive[archive.files[0]]
            else:
                raise RestyleContractError(f"ambiguous NPZ arrays in {path.name}")
            return np.asarray(array).copy()
    except (OSError, ValueError) as exc:
        raise RestyleContractError(f"cannot read {path}: {exc}") from exc


def _mask(path: Path, shape: tuple[int, int]) -> np.ndarray:
    value = _load_npz_array(path)
    if value.shape != shape:
        raise RestyleContractError(
            f"mask shape mismatch for {path.name}: {value.shape} != {shape}"
        )
    return value != 0


def _resolution_from_plan(plan: Mapping[str, Any]) -> tuple[int, int] | None:
    value = plan.get("image_resolution_px")
    if isinstance(value, list) and len(value) == 2:
        return int(value[0]), int(value[1])
    if isinstance(value, dict):
        width = value.get("width") or value.get("width_px")
        height = value.get("height") or value.get("height_px")
        if width is not None and height is not None:
            return int(width), int(height)
    return None


